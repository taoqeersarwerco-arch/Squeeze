/**
 * Raster-to-SVG Vectorizer and SVG Generator.
 * Quantizes image colors and creates scalable vector paths, plus provides high-fidelity vector container generation.
 */

export interface TraceOptions {
  detail: 'low' | 'medium' | 'high';
  preserveColors?: boolean;
}

/**
 * Traces bitmap image data into scalable SVG vector paths using color quantization and horizontal run vectorization.
 */
export function traceBitmapToSvg(
  imageData: ImageData,
  options: TraceOptions = { detail: 'medium' }
): string {
  const { width, height, data } = imageData;
  
  // Step factor based on detail
  const step = options.detail === 'high' ? 1 : options.detail === 'medium' ? 2 : 4;
  const numColorLevels = options.detail === 'high' ? 16 : options.detail === 'medium' ? 8 : 4;
  const quantStep = 256 / numColorLevels;

  function quantize(val: number): number {
    return Math.min(255, Math.floor(val / quantStep) * quantStep + Math.floor(quantStep / 2));
  }

  // Map of color hex -> array of path segments
  const colorPaths = new Map<string, string[]>();

  for (let y = 0; y < height; y += step) {
    let startX = -1;
    let currentColor = '';

    for (let x = 0; x < width; x += step) {
      const idx = (y * width + x) * 4;
      const a = data[idx + 3];

      if (a < 32) {
        // Transparent pixel - close run if open
        if (startX !== -1 && currentColor) {
          const runW = x - startX;
          const rectPath = `M${startX},${y}h${runW}v${step}h${-runW}Z`;
          if (!colorPaths.has(currentColor)) colorPaths.set(currentColor, []);
          colorPaths.get(currentColor)!.push(rectPath);
          startX = -1;
          currentColor = '';
        }
        continue;
      }

      const r = quantize(data[idx]);
      const g = quantize(data[idx + 1]);
      const b = quantize(data[idx + 2]);
      const hex = `#${((1 << 24) + (r << 16) + (g << 8) + b).toString(16).slice(1)}`;

      if (hex !== currentColor) {
        if (startX !== -1 && currentColor) {
          const runW = x - startX;
          const rectPath = `M${startX},${y}h${runW}v${step}h${-runW}Z`;
          if (!colorPaths.has(currentColor)) colorPaths.set(currentColor, []);
          colorPaths.get(currentColor)!.push(rectPath);
        }
        startX = x;
        currentColor = hex;
      }
    }

    if (startX !== -1 && currentColor) {
      const runW = width - startX;
      const rectPath = `M${startX},${y}h${runW}v${step}h${-runW}Z`;
      if (!colorPaths.has(currentColor)) colorPaths.set(currentColor, []);
      colorPaths.get(currentColor)!.push(rectPath);
    }
  }

  // Assemble SVG XML
  const pathsXml: string[] = [];
  colorPaths.forEach((runs, color) => {
    if (runs.length > 0) {
      pathsXml.push(`<path fill="${color}" d="${runs.join(' ')}" shape-rendering="crispEdges"/>`);
    }
  });

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">
  <!-- Generated by Squeeze (https://squeeze.app) -->
  <g id="vector-layer">
    ${pathsXml.join('\n    ')}
  </g>
</svg>`;
}

/**
 * Creates a high-fidelity SVG document that embeds the bitmap data URL with responsive viewBox.
 */
export function createEmbeddedSvg(
  dataUrl: string,
  width: number,
  height: number
): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">
  <!-- High-fidelity Vector Container generated by Squeeze -->
  <image href="${dataUrl}" width="${width}" height="${height}" preserveAspectRatio="xMidYMid meet"/>
</svg>`;
}
